# Завдання 1
# Користувач вводить рядок та індекс. Виведіть символ
# під цим індексом. Якщо індекс завеликий, виведіть
# інформацію про помилку.

text = input("Введіть рядок: ")
index = int(input("Введіть індекс: "))

if 0 <= index < len(text):
    print(f"Символ під індексом {index}: {text[index]}")
else:
    print("Помилка: такого індексу немає")
